"""Restore tables dropped by an autogenerate accident in 62cb82f2dc52.

That migration was titled "add api_url to llm_model_configs", but its
autogenerated ``upgrade`` also dropped ``location_profiles``,
``localith_connections`` and ``location_posts``. A database provisioned from
migrations alone returned 500 for locations and the posts feed. The
development database masked the bug because its tables were created out of
band.

This revision creates the two tables the product still uses, using the current
model definitions, and is a no-op on databases that still have them. The
retired ``localith_connections`` table is intentionally not restored: it is
dropped by the Localith-retirement migration, and restoring it here would make
fresh databases depend on a model that no longer exists.

``downgrade`` deliberately does nothing. Dropping application tables is the
bug this revision exists to undo, not a state a downgrade should recreate.
"""
import app.main  # noqa: F401 - registers every model on Base.metadata
from alembic import op

from app.database import Base

revision = "d5e6f7a8b9c0d1"
down_revision = "c4d5e6f7a8b9c0"
branch_labels = None
depends_on = None

# Tables the accidental migration removed that the product still uses. Order
# matters only for readability; Table.create resolves foreign keys against the
# fully-populated metadata.
_RESTORED_TABLES = (
    "location_profiles",
    "location_posts",
)


def upgrade() -> None:
    bind = op.get_bind()
    for table_name in _RESTORED_TABLES:
        table = Base.metadata.tables[table_name]
        # checkfirst=True makes the repair idempotent: an environment that
        # never lost the table is untouched.
        table.create(bind, checkfirst=True)


def downgrade() -> None:
    # Intentionally empty: this revision restores application tables, it does
    # not own them. Dropping them on downgrade would reintroduce the outage.
    pass
